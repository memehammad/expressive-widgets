#!/usr/bin/env python3
"""Generates the Material 3 Expressive shape set as white vectors (tinted at runtime).

Each shape: drawable/shp_<name>.xml (48x48 viewport) and its id in Shapes.kt.
Run from the project root:  python3 tools/gen_shapes.py
"""
import math
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
RES = os.path.join(ROOT, "app", "src", "main", "res", "drawable")
KT = os.path.join(ROOT, "app", "src", "main", "java", "dev", "memehammad", "widgets", "Shapes.kt")
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_shapes.py -->\n'
N = 48.0
C = N / 2


def polar(fn, steps=240, rot=-math.pi / 2):
    pts = []
    for i in range(steps):
        a = 2 * math.pi * i / steps
        r = fn(a)
        pts.append((C + r * math.cos(a + rot), C + r * math.sin(a + rot)))
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + "Z"


def lobed(lobes, depth, r=C):
    return polar(lambda a: r * ((1 - depth) + depth * math.cos(lobes * a)))


def sharp(points, depth, r=C, power=2.5):
    """Star with soft tips: narrow peaks and broad valleys ((1+cos)/2 raised to a power)."""
    def f(a):
        k = ((1 + math.cos(points * a)) / 2) ** power
        return r * ((1 - depth) + depth * k)
    return polar(f, steps=360)


def superellipse(n=4.0, r=C):
    def f(a):
        c, s = abs(math.cos(a)), abs(math.sin(a))
        return r / ((c ** n + s ** n) ** (1 / n))
    return polar(f, rot=0)


def rounded_poly(sides, r=C, round_=0.35, rot=-math.pi / 2):
    """Regular polygon with smoothly rounded corners (blend towards a circle)."""
    def f(a):
        k = math.pi / sides
        x = (a % (2 * k)) - k
        poly = r * math.cos(k) / math.cos(x)
        return (1 - round_) * poly + round_ * r * 0.92
    return polar(f, rot=rot)


def pill():
    """Horizontal capsule."""
    return "M18,10 H30 A14,14 0 0 1 30,38 H18 A14,14 0 0 1 18,10 Z"


def arch():
    return "M4,44 V24 A20,20 0 0 1 44,24 V44 Z"


def heart():
    return ("M24,43 C20,39 4,30 4,17 C4,9 10,4 16,4 C20,4 23,6 24,9 "
            "C25,6 28,4 32,4 C38,4 44,9 44,17 C44,30 28,39 24,43 Z")


SHAPES = {
    "circle": polar(lambda a: C),
    "squircle": superellipse(4.0),
    "square": superellipse(9.0, r=C * 0.98),
    "pill": pill(),
    "arch": arch(),
    "cookie4": lobed(4, 0.14),
    "cookie6": lobed(6, 0.10),
    "cookie9": lobed(9, 0.07),
    "cookie12": lobed(12, 0.05),
    "clover": lobed(4, 0.2),
    "flower": lobed(8, 0.16),
    "sunny": sharp(8, 0.16, power=2.0),
    "burst": sharp(12, 0.24, power=3.0),
    "gem": rounded_poly(4, round_=0.25, rot=0),
    "pentagon": rounded_poly(5, round_=0.3),
    "heart": heart(),
}

LABELS = {
    "circle": "Circle", "squircle": "Squircle", "square": "Rounded square", "pill": "Pill",
    "arch": "Arch", "cookie4": "4-sided cookie", "cookie6": "6-sided cookie",
    "cookie9": "9-sided cookie", "cookie12": "12-sided cookie", "clover": "Clover",
    "flower": "Flower", "sunny": "Sunny", "burst": "Burst", "gem": "Gem",
    "pentagon": "Pentagon", "heart": "Heart",
}


def main():
    os.makedirs(RES, exist_ok=True)
    for name, path in SHAPES.items():
        with open(os.path.join(RES, f"shp_{name}.xml"), "w") as f:
            f.write(
                HEADER
                + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
                '    android:width="48dp" android:height="48dp"\n'
                '    android:viewportWidth="48" android:viewportHeight="48">\n'
                f'    <path android:fillColor="#FFFFFFFF" android:pathData="{path}" />\n'
                "</vector>\n"
            )
    for name in SHAPES:
        with open(os.path.join(RES, f"shp_{name}_fill.xml"), "w") as f:
            f.write(
                HEADER
                + '<!-- Shape filled from the bottom by the image level (0-10000), e.g. battery. -->\n'
                '<clip xmlns:android="http://schemas.android.com/apk/res/android"\n'
                '    android:clipOrientation="vertical"\n'
                f'    android:drawable="@drawable/shp_{name}"\n'
                '    android:gravity="bottom" />\n'
            )
    entries = "".join(
        f'        Shape("{n}", "{LABELS[n]}", R.drawable.shp_{n}, R.drawable.shp_{n}_fill),\n' for n in SHAPES
    )
    with open(KT, "w") as f:
        f.write(
            "package dev.memehammad.widgets\n\n"
            "// Generated by tools/gen_shapes.py\n\n"
            "data class Shape(val id: String, val label: String, val res: Int, val fill: Int)\n\n"
            "object Shapes {\n"
            "    val all = listOf(\n" + entries + "    )\n\n"
            "    fun byId(id: String?): Shape = all.firstOrNull { it.id == id } ?: all.first { it.id == \"cookie9\" }\n"
            "}\n"
        )
    print(f"{len(SHAPES)} shapes")


if __name__ == "__main__":
    main()
