#!/usr/bin/env python3
"""Turns tools/shapes.json (the official Material 3 Expressive shapes, computed with Google's
androidx.graphics.shapes library by tools/shapegen/Gen.kt) into Android resources:

  drawable/shp_<id>.xml          static white vector (tinted at runtime)
  drawable/spa_<id>.xml          slowly spinning version (animated vector)
  layout/sp_<id>.xml             ProgressBar host for the spinning version (widgets only animate there)
  drawable/lq_<id>_<pct>.xml     battery liquid: the shape filled to <pct> with two moving waves
  layout/lql_<id>_<pct>.xml      ProgressBar host for the liquid
  drawable/mo_<name>.xml         morphing decorations (+ layout/ml_<name>.xml)
  Shapes.kt                      the shape catalogue

Run from anywhere:  python3 tools/gen_shapes.py
"""
import glob
import json
import math
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
RES = os.path.join(ROOT, "app", "src", "main", "res")
KT = os.path.join(ROOT, "app", "src", "main", "java", "dev", "memehammad", "widgets", "Shapes.kt")
HEAD = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_shapes.py -->\n'
A = 'xmlns:android="http://schemas.android.com/apk/res/android"'
AAPT = 'xmlns:aapt="http://schemas.android.com/aapt"'

data = json.load(open(os.path.join(ROOT, "tools", "shapes.json")))
SHAPES = data["shapes"]
MORPHS = data["morphs"]

# Picker order and labels.
ORDER = [
    ("circle", "Circle"), ("square", "Square"), ("cookie4", "4-sided cookie"), ("cookie6", "6-sided cookie"),
    ("cookie7", "7-sided cookie"), ("cookie9", "9-sided cookie"), ("cookie12", "12-sided cookie"),
    ("sunny", "Sunny"), ("verysunny", "Very sunny"), ("clover4", "4-leaf clover"), ("clover8", "8-leaf clover"),
    ("flower", "Flower"), ("puffy", "Puffy"), ("puffydiamond", "Puffy diamond"), ("softburst", "Soft burst"),
    ("burst", "Burst"), ("softboom", "Soft boom"), ("boom", "Boom"), ("ghostish", "Ghost-ish"), ("bun", "Bun"),
    ("heart", "Heart"), ("gem", "Gem"), ("pentagon", "Pentagon"), ("diamond", "Diamond"), ("triangle", "Triangle"),
    ("arrow", "Arrow"), ("arch", "Arch"), ("fan", "Fan"), ("slanted", "Slanted"), ("semicircle", "Semicircle"),
    ("oval", "Oval"), ("pill", "Pill"), ("clamshell", "Clamshell"), ("pixelcircle", "Pixel circle"),
    ("pixeltriangle", "Pixel triangle"),
]
assert sorted(i for i, _ in ORDER) == sorted(SHAPES), "shape list out of sync"

# Shapes offered for the battery liquid (each needs 21 generated levels).
LIQUID = ["square", "circle", "cookie4", "cookie6", "cookie9", "cookie12", "sunny", "clover4", "clover8",
          "ghostish", "puffy", "heart", "flower", "pill", "arch", "gem"]
LEVELS = list(range(0, 101, 5))


def points(path):
    nums = [float(n) for n in re.findall(r"-?\d+\.?\d*", path)]
    return list(zip(nums[0::2], nums[1::2]))


def write(sub, name, text):
    d = os.path.join(RES, sub)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, name), "w") as f:
        f.write(HEAD + text)


def vector(body, size=100):
    return (f'<vector {A}\n    android:width="{size}dp" android:height="{size}dp"\n'
            f'    android:viewportWidth="100" android:viewportHeight="100">\n{body}</vector>\n')


def host(drawable, comment):
    """ProgressBar layout that runs an animated drawable (the only way widgets animate)."""
    return (f'<!-- {comment} -->\n'
            f'<ProgressBar {A}\n'
            f'    android:id="@+id/blob"\n'
            f'    style="@android:style/Widget.Material.ProgressBar.Horizontal"\n'
            f'    android:layout_width="match_parent"\n'
            f'    android:layout_height="match_parent"\n'
            f'    android:indeterminate="true"\n'
            f'    android:indeterminateOnly="true"\n'
            f'    android:indeterminateDrawable="@drawable/{drawable}"\n'
            f'    android:minWidth="0dp" android:minHeight="0dp"\n'
            f'    android:maxWidth="2000dp" android:maxHeight="2000dp" />\n')


def avd(vector_xml, targets):
    t = "".join(
        f'    <target android:name="{name}">\n        <aapt:attr name="android:animation">\n{anim}'
        f'        </aapt:attr>\n    </target>\n'
        for name, anim in targets
    )
    inner = "\n".join("            " + l for l in vector_xml.strip().split("\n"))
    return (f'<animated-vector {A}\n    {AAPT}>\n    <aapt:attr name="android:drawable">\n{inner}\n'
            f'    </aapt:attr>\n{t}</animated-vector>\n')


def anim(prop, frm, to, ms, reverse=False, vtype="floatType", interp="@android:interpolator/linear"):
    rep = ' android:repeatMode="reverse"' if reverse else ""
    return (f'            <objectAnimator android:propertyName="{prop}" android:valueFrom="{frm}"\n'
            f'                android:valueTo="{to}" android:valueType="{vtype}" android:duration="{ms}"\n'
            f'                android:repeatCount="infinite"{rep} android:interpolator="{interp}" />\n')


def curve(path, steps=24):
    """Dense boundary samples of an M..C..Z path."""
    nums = [float(n) for n in re.findall(r"-?\d+\.?\d*", path)]
    x0, y0 = nums[0], nums[1]
    out = []
    i = 2
    while i + 5 < len(nums):
        x1, y1, x2, y2, x3, y3 = nums[i:i + 6]
        for k in range(steps):
            t = k / steps
            u = 1 - t
            out.append((u ** 3 * x0 + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t ** 3 * x3,
                        u ** 3 * y0 + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t ** 3 * y3))
        x0, y0 = x3, y3
        i += 6
    return out


def inner_box(path):
    """Largest square inside the shape: (centre x, centre y, half size), all 0..1."""
    pts = curve(path)
    best = (50.0, 50.0, 0.0)
    for cx in range(30, 71, 2):
        for cy in range(30, 71, 2):
            a = min(max(abs(x - cx), abs(y - cy)) for x, y in pts)
            if a > best[2]:
                best = (cx, cy, a)
    cx, cy, a = best
    return cx / 100, cy / 100, a * 0.97 / 100


def spin_scale(path):
    r = max(math.hypot(x - 50, y - 50) for x, y in points(path))
    return min(1.0, 50.0 / r) if r > 0 else 1.0


def wave(y, amp, length=50.0, x0=-100.0, x1=200.0):
    """A sine-like wave (smooth quadratics) at height y, closed below the viewport."""
    q = length / 4
    d = f"M{x0:.1f},{y:.2f}"
    x = x0
    up = True
    while x < x1:
        cy = y - 2 * amp if up else y + 2 * amp
        d += f" Q{x + q:.2f},{cy:.2f} {x + 2 * q:.2f},{y:.2f}"
        x += 2 * q
        up = not up
    return d + f" L{x:.1f},120 L{x0:.1f},120 Z"


def clean():
    pats = ["drawable/shp_*.xml", "drawable/spa_*.xml", "drawable/lq_*.xml", "drawable/mo_*.xml",
            "layout/sp_*.xml", "layout/lql_*.xml", "layout/ml_*.xml"]
    for p in pats:
        for f in glob.glob(os.path.join(RES, p)):
            os.remove(f)


def main():
    clean()
    for sid, path in SHAPES.items():
        write("drawable", f"shp_{sid}.xml", vector(f'    <path android:fillColor="#FFFFFFFF" android:pathData="{path}" />\n', size=400))
        s = spin_scale(path)
        spin_vec = vector(
            f'    <group android:name="r" android:pivotX="50" android:pivotY="50" android:scaleX="{s:.3f}" android:scaleY="{s:.3f}">\n'
            f'        <path android:fillColor="#FFFFFFFF" android:pathData="{path}" />\n    </group>\n')
        write("drawable", f"spa_{sid}.xml", avd(spin_vec, [("r", anim("rotation", 0, 360, 30000))]))
        write("layout", f"sp_{sid}.xml", host(f"spa_{sid}", f"{sid}, slowly spinning"))

    for sid in LIQUID:
        path = SHAPES[sid]
        ys = [y for _, y in points(path)]
        top, bottom = max(0.0, min(ys)), min(100.0, max(ys))
        amp = 4.0
        for pct in LEVELS:
            span = bottom - top + 4 * amp + 2
            y = bottom + 2 * amp + 1 - span * pct / 100.0
            body = (
                '    <group>\n'
                f'        <clip-path android:pathData="{path}" />\n'
                '        <group android:name="back">\n'
                f'            <path android:fillColor="#FFFFFFFF" android:fillAlpha="0.4" android:pathData="{wave(y - 2.5, amp * 0.9)}" />\n'
                '        </group>\n'
                '        <group android:name="front">\n'
                f'            <path android:fillColor="#FFFFFFFF" android:pathData="{wave(y, amp)}" />\n'
                '        </group>\n'
                '    </group>\n'
            )
            name = f"lq_{sid}_{pct:03d}"
            write("drawable", name + ".xml", avd(vector(body), [
                ("front", anim("translateX", 0, -50, 2200)),
                ("back", anim("translateX", -50, 0, 3400)),
            ]))
            write("layout", f"lql_{sid}_{pct:03d}.xml", host(name, f"battery liquid: {sid} at {pct}%"))

    # Morphing decorations: shape A <-> shape B while turning.
    named = {"sunny>verysunny": "sun", "cookie9>softburst": "charge", "circle>cookie12": "pulse"}
    for pair, (a, b) in MORPHS.items():
        n = named[pair]
        body = (
            '    <group android:name="r" android:pivotX="50" android:pivotY="50" android:scaleX="0.94" android:scaleY="0.94">\n'
            f'        <path android:name="p" android:fillColor="#FFFFFFFF" android:pathData="{a}" />\n'
            '    </group>\n'
        )
        write("drawable", f"mo_{n}.xml", avd(vector(body), [
            ("r", anim("rotation", 0, 360, 16000)),
            ("p", anim("pathData", a, b, 1600, reverse=True, vtype="pathType",
                       interp="@android:interpolator/fast_out_slow_in")),
        ]))
        write("layout", f"ml_{n}.xml", host(f"mo_{n}", f"morphing {pair}"))

    # Kotlin catalogue.
    lines = [
        "package dev.memehammad.widgets", "",
        "// Generated by tools/gen_shapes.py from the official Material 3 Expressive shapes.", "",
        "/** [res] static vector, [spin] layout with the same shape slowly turning. */",
        "data class Shape(val id: String, val label: String, val res: Int, val spin: Int, val box: Box, val spinBox: Box)", "",
        "/** [box] is where text fits; [spinBox] where it fits while the shape turns. */", "",
        "/** Largest square that fits inside a shape: centre and half size, as fractions of the shape's size. */",
        "data class Box(val cx: Float, val cy: Float, val half: Float)", "",
        "object Shapes {",
        "    val all = listOf(",
    ]
    for sid, label in ORDER:
        cx, cy, h = inner_box(SHAPES[sid])
        rin = min(math.hypot(x - 50, y - 50) for x, y in curve(SHAPES[sid])) * spin_scale(SHAPES[sid])
        sh = rin / math.sqrt(2) * 0.97 / 100
        lines.append(f'        Shape("{sid}", "{label}", R.drawable.shp_{sid}, R.layout.sp_{sid}, '
                     f'Box({cx:.3f}f, {cy:.3f}f, {h:.3f}f), Box(0.5f, 0.5f, {sh:.3f}f)),')
    lines += [
        "    )", "",
        "    /** Old ids from the first version map to their closest official shape. */",
        '    private val legacy = mapOf("squircle" to "square", "clover" to "clover4")', "",
        "    fun byId(id: String?): Shape = all.firstOrNull { it.id == (legacy[id] ?: id) } ?: all.first { it.id == \"cookie9\" }",
        "}", "",
        "/** Battery liquid: the shape filled to a level (5 % steps) with moving waves. */",
        "object Liquid {",
        "    val shapes = listOf(" + ", ".join(f'"{s}"' for s in LIQUID) + ")", "",
        "    private val layouts = mapOf(",
    ]
    for sid in LIQUID:
        refs = ", ".join(f"R.layout.lql_{sid}_{p:03d}" for p in LEVELS)
        lines.append(f'        "{sid}" to intArrayOf({refs}),')
    lines += [
        "    )", "",
        "    fun supports(id: String) = id in layouts",
        "",
        "    fun layout(id: String, level: Int): Int {",
        "        val arr = layouts[id] ?: layouts.getValue(\"square\")",
        "        return arr[((level.coerceIn(0, 100) + 2) / 5).coerceIn(0, arr.lastIndex)]",
        "    }",
        "}", "",
        "/** Morphing decorations. */",
        "object Morphs {",
        "    val sun = R.layout.ml_sun",
        "    val charge = R.layout.ml_charge",
        "    val pulse = R.layout.ml_pulse",
        "    val stars = R.layout.ml_stars",
        "}", "",
    ]
    with open(KT, "w") as f:
        f.write("\n".join(lines))
    print(f"{len(SHAPES)} shapes, {len(LIQUID) * len(LEVELS)} liquid levels, {len(MORPHS)} morphs")


if __name__ == "__main__":
    main()
    # The moon frames and twinkling stars live in their own script (and share the mo_/ml_ names).
    import subprocess, sys
    subprocess.run([sys.executable, os.path.join(ROOT, "tools", "gen_moon.py")], check=True)
