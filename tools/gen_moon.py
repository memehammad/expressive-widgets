#!/usr/bin/env python3
"""Moon phase drawables (24 steps, with craters and a soft night side) and a twinkling-stars
animation for the Moon widget. Run from anywhere: python3 tools/gen_moon.py"""
import math
import os

RES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "src", "main", "res")
NS = 'xmlns:android="http://schemas.android.com/apk/res/android"'
AAPT = 'xmlns:aapt="http://schemas.android.com/aapt"'
DISC = "M50,8 A42,42 0 1,1 50,92 A42,42 0 1,1 50,8 Z"
LIT = "#FFFFF3C4"
CRATER = "#FFEBD58A"
NIGHT = "#8C1B1236"
CRATERS = [(36, 34, 7), (60, 26, 4.5), (64, 56, 9), (40, 66, 5.5), (28, 52, 3.5), (52, 80, 3.5)]


def circle(cx, cy, r):
    return f"M{cx - r:.2f},{cy:.2f} a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0 a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0 Z"


def lit_path(p):
    r = 42
    if p < 0.02 or p > 0.98:
        return None
    if abs(p - 0.5) < 0.02:
        return DISC
    rx = max(abs(math.cos(2 * math.pi * p)) * r, 0.01)
    waxing = p < 0.5
    q = p if waxing else 1 - p
    crescent = q < 0.25
    outer = 1 if waxing else 0
    term = (0 if crescent else 1) if waxing else (1 if crescent else 0)
    return f"M50,8 A42,42 0 0,{outer} 50,92 A{rx:.2f},42 0 0,{term} 50,8 Z"


def write(sub, name, text):
    with open(os.path.join(RES, sub, name), "w") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_moon.py -->\n' + text)


for k in range(24):
    p = k / 24
    lit = lit_path(p)
    craters = "".join(circle(*c) for c in CRATERS)
    body = f'    <path android:fillColor="{NIGHT}" android:pathData="{DISC}" />\n'
    # Faint craters on the night side too, so the whole moon reads as a ball.
    body += f'    <path android:fillColor="#26FFFFFF" android:pathData="{craters}" />\n'
    if lit:
        body += (f'    <group>\n        <clip-path android:pathData="{lit}" />\n'
                 f'        <path android:fillColor="{LIT}" android:pathData="{DISC}" />\n'
                 f'        <path android:fillColor="{CRATER}" android:pathData="{craters}" />\n    </group>\n')
    write("drawable", f"moon_{k:02d}.xml",
          f'<vector {NS}\n    android:width="100dp" android:height="100dp"\n'
          f'    android:viewportWidth="100" android:viewportHeight="100">\n{body}</vector>\n')

# Twinkling stars: four-point sparkles that grow, shrink and turn, out of step with each other.
STARS = [(14, 18, 9, 1300, 0), (86, 14, 6, 1700, 400), (90, 70, 8, 1500, 900), (10, 78, 5.5, 1900, 200), (70, 92, 4.5, 1100, 600)]
spark = "M0,-1 Q0.16,-0.16 1,0 Q0.16,0.16 0,1 Q-0.16,0.16 -1,0 Q-0.16,-0.16 0,-1 Z"
groups = ""
targets = ""
for i, (x, y, s, ms, off) in enumerate(STARS):
    groups += (f'                <group android:translateX="{x}" android:translateY="{y}">\n'
               f'                    <group android:name="s{i}" android:scaleX="{s}" android:scaleY="{s}">\n'
               f'                        <path android:fillColor="#FFFFFFFF" android:pathData="{spark}" />\n'
               f'                    </group>\n                </group>\n')
    anims = "".join(
        f'                    <objectAnimator android:propertyName="{prop}" android:valueFrom="{a}" android:valueTo="{b}"\n'
        f'                        android:valueType="floatType" android:duration="{ms}" android:startOffset="{off}"\n'
        f'                        android:repeatCount="infinite" android:repeatMode="reverse"\n'
        f'                        android:interpolator="@android:interpolator/fast_out_slow_in" />\n'
        for prop, a, b in [("scaleX", s * 0.25, s), ("scaleY", s * 0.25, s), ("rotation", 0, 90)])
    targets += (f'    <target android:name="s{i}">\n        <aapt:attr name="android:animation">\n'
                f'            <set>\n{anims}            </set>\n        </aapt:attr>\n    </target>\n')
write("drawable", "mo_stars.xml",
      f'<animated-vector {NS}\n    {AAPT}>\n    <aapt:attr name="android:drawable">\n'
      f'        <vector android:width="100dp" android:height="100dp"\n'
      f'            android:viewportWidth="100" android:viewportHeight="100">\n{groups}        </vector>\n'
      f'    </aapt:attr>\n{targets}</animated-vector>\n')
write("layout", "ml_stars.xml",
      f'<!-- Twinkling stars -->\n<ProgressBar {NS}\n    android:id="@+id/blob"\n'
      '    style="@android:style/Widget.Material.ProgressBar.Horizontal"\n'
      '    android:layout_width="match_parent"\n    android:layout_height="match_parent"\n'
      '    android:indeterminate="true"\n    android:indeterminateOnly="true"\n'
      '    android:indeterminateDrawable="@drawable/mo_stars"\n'
      '    android:minWidth="0dp" android:minHeight="0dp"\n'
      '    android:maxWidth="2000dp" android:maxHeight="2000dp" />\n')
print("moon + stars written")
